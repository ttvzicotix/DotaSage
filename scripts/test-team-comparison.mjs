import assert from 'node:assert/strict';
import { matchupEdge, alliedPair, draftTeam } from '../src/engine/teamComparison.js';
const self = { id: 1, roles: ['Carry'], localized_name: 'Carry' };
const ally = { id: 2, roles: ['Support', 'Disabler'], localized_name: 'Support' };
assert.deepEqual(draftTeam(self, [self, ally]).map(h => h.id), [1,2]);
assert.deepEqual(draftTeam(null, [ally]), [ally]);
assert.equal(matchupEdge([], 3), null);
assert.equal(matchupEdge([{hero_id:3, games_played:0, wins:0}], 3), null);
assert.equal(matchupEdge([{hero_id:3, games_played:10, wins:20}], 3), null);
const rows = [{hero_id:3, games_played:100, wins:60}, {hero_id:4,games_played:100,wins:40}];
assert.ok(Math.abs(matchupEdge(rows, 3).edge - 10) < 0.0001);
assert.ok(Math.abs(matchupEdge(rows, 4).edge + 10) < 0.0001);
assert.equal(matchupEdge(rows, 5), null);
const unknown = alliedPair(self, ally, new Map());
assert.equal(unknown.winRate, null);
assert.ok(unknown.modeled > 0);
assert.match(unknown.explanation, /support, disabler/);
const reverse = alliedPair(self, ally, new Map([[2,{synergy:[{hero_id:1,games_played:100,wins:57}]}]]));
assert.ok(Math.abs(reverse.winRate - 57) < 0.0001);
assert.equal(reverse.n,100);
console.log('Team matrix orientation, missing samples, reverse synergy and modeled complement: PASS');
